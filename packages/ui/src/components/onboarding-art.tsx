import { Image } from 'expo-image'
import { type ReactElement, useState } from 'react'
import { Pressable, Text, View } from 'react-native'
import Animated, { useReducedMotion, ZoomIn, ZoomOut } from 'react-native-reanimated'
import { onSpace } from './space-press'

const OUTLINE = require('../../assets/images/star-outline.png')
const SOLID = require('../../assets/images/star-solid.png')

interface StarProps {
  size: number
  color: string
  hollow?: boolean
  opacity?: number
}

/**
 * The eight-point star, drawn from the same stamps as the app icon rather than
 * from two overlapping squares. The union matters: composed squares show their
 * crossing lines when outlined, and a darker patch where they meet when shaded.
 * The stamps are white, so `tintColor` paints them from the palette.
 *
 * Generated by `scripts/build-brand-assets.ts`, which is also what draws the
 * icon, so the mark on screen and the mark on the home screen cannot drift.
 */
function Star({ size, color, hollow = false, opacity = 1 }: StarProps): ReactElement {
  return (
    <Image
      source={hollow ? OUTLINE : SOLID}
      tintColor={color}
      contentFit="contain"
      // Decorative: hidden from every screen reader.
      accessible={false}
      accessibilityElementsHidden
      importantForAccessibility="no-hide-descendants"
      aria-hidden
      style={{ width: size, height: size, opacity }}
    />
  )
}

interface OnboardingArtProps {
  variant: 'welcome' | 'how'
  color: string
  onColor: string
  /** The example circle's name for screen readers, on the 'how' variant. */
  checkLabel?: string
}

const GRID = [0.3, 0.55, 0.3, 0.55, 1, 0.55, 0.3, 0.55, 0.3]
const CIRCLE = 52

interface Thing {
  checked: boolean
}

interface ExampleCheckProps {
  color: string
  onColor: string
  label: string | undefined
}

/**
 * The circle the 'how' step talks about, so it can be tried right there: a
 * tap ticks it or clears it. Local state only; it records nothing.
 */
function ExampleCheck({ color, onColor, label }: ExampleCheckProps): ReactElement {
  const [thing, setThing] = useState<Thing>({ checked: true })
  const { checked } = thing
  const reduceMotion = useReducedMotion()
  const toggle = (): void => setThing((current) => ({ checked: !current.checked }))

  return (
    <Pressable
      accessibilityRole="checkbox"
      accessibilityState={{ checked }}
      // react-native-web reads only the aria-* form.
      aria-checked={checked}
      accessibilityLabel={label}
      onPress={toggle}
      // A checkbox toggles on Space; react-native-web only answers Enter here.
      onKeyDown={onSpace(toggle)}
      hitSlop={12}
      className="items-center justify-center rounded-full"
      style={{ width: CIRCLE, height: CIRCLE, borderWidth: 2, borderColor: color }}>
      {checked ? (
        <Animated.View
          entering={reduceMotion ? undefined : ZoomIn.duration(200)}
          exiting={reduceMotion ? undefined : ZoomOut.duration(150)}
          className="items-center justify-center rounded-full"
          // Over the ring, not inside it, so the filled circle is the same size.
          style={{
            position: 'absolute',
            top: -2,
            start: -2,
            width: CIRCLE,
            height: CIRCLE,
            backgroundColor: color,
          }}>
          <Text
            aria-hidden
            accessibilityElementsHidden
            importantForAccessibility="no"
            style={{ color: onColor, fontSize: 26 }}>
            ✓
          </Text>
        </Animated.View>
      ) : null}
    </Pressable>
  )
}

export function OnboardingArt({
  variant,
  color,
  onColor,
  checkLabel,
}: OnboardingArtProps): ReactElement {
  if (variant === 'how') {
    return (
      <View className="items-center justify-center" style={{ width: 208, height: 208 }}>
        <View style={{ position: 'absolute' }}>
          <Star size={208} color={color} hollow />
        </View>
        <ExampleCheck color={color} onColor={onColor} label={checkLabel} />
      </View>
    )
  }

  return (
    <View className="flex-row flex-wrap justify-center" style={{ width: 228 }}>
      {GRID.map((opacity, index) => (
        <View key={index} style={{ padding: 6 }}>
          <Star size={64} color={color} hollow={index % 2 === 0 && index !== 4} opacity={opacity} />
        </View>
      ))}
    </View>
  )
}
